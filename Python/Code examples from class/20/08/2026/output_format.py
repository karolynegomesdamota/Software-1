lunch_time = 1145

print ("My lunch time today will be " + str(lunch_time))
print (f"My lunch time today will be {lunch_time}")
# These should look exactly the same, it's just a different way of coding.

print (f"My lunch time today will be {lunch_time:6.2f}")
print (f"My lunch time today will be {lunch_time:6.4f}")
print (f"My lunch time today will be {lunch_time:10.4f}")
print (f"My lunch time today will be {lunch_time:15.4f}")
# We are saying with the first digits how many spaces we want for integral numbers and the second one decimals.
